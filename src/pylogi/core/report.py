"""Compatibility report: what pyLogi found on this computer, safe to attach to a bug report.

Nothing is written to any device.  Serial numbers and unit ids are left out unless asked for,
and the user name / home folder never appear.
"""
from __future__ import annotations

import json
import platform
import sys
import time
from typing import Any

from .. import __version__
from .device import Device


def _device(dev: Device, serials: bool) -> dict[str, Any]:
    info = dev.info
    out: dict[str, Any] = {
        "name": dev.name, "kind": dev.kind, "connection": dev.connection, "online": dev.online,
        "model_ids": list(getattr(dev, "model_ids", []) or []),
        "capabilities": sorted(dev.caps),
        "hidpp_features": info.extra.get("Features", ""),
    }
    if getattr(info, "firmware", ""):
        out["firmware"] = info.firmware
    if dev.battery is not None:
        out["battery"] = {"percent": dev.battery.percent, "charging": dev.battery.charging}
    if serials:
        out["serial"], out["unit"] = info.serial, info.unit
    return out


def build(devices: list[Device], serials: bool = False) -> dict[str, Any]:
    try:
        from PySide6 import __version__ as qt
    except ImportError:                                        # pragma: no cover
        qt = "?"
    return {
        "pylogi": __version__,
        "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "system": {"os": platform.system(), "release": platform.release(), "machine": platform.machine(),
                   "python": sys.version.split()[0], "pyside6": qt},
        "devices": [_device(d, serials) for d in devices if d.kind != "receiver"],
        "receivers": [{"name": d.name, "connection": d.connection} for d in devices if d.kind == "receiver"],
        "note": "Generated by 'pylogi --report'. Read-only: nothing was written to any device.",
    }


def to_text(report: dict[str, Any]) -> str:
    return json.dumps(report, indent=1, ensure_ascii=False)
