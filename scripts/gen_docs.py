"""Regenerate the generated parts of the documentation (README tables and THIRD_PARTY.md).

    python scripts/gen_docs.py          # rewrite the files
    python scripts/gen_docs.py --check  # exit 1 if they are out of date (used by the tests / CI)
"""
import os
import re
import sys
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from pylogi.core import credits  # noqa: E402


def cli_markdown() -> str:
    from pylogi.app import build_parser
    rows = ["| Option | Description |", "|---|---|"]
    for a in build_parser()._actions:
        if not a.option_strings:
            continue
        names = ", ".join(f"`{o}`" for o in a.option_strings)
        meta = a.metavar if isinstance(a.metavar, str) else (" ".join(a.metavar) if a.metavar else "")
        if meta:
            names += f" `{meta}`"
        elif a.choices:
            names += " `{" + "|".join(map(str, a.choices)) + "}`"
        rows.append(f"| {names} | {a.help or ''} |")
    return "\n".join(rows)


def components_markdown() -> str:
    rows = ["| Component | Licence | Role |", "|---|---|---|"]
    for c in credits.COMPONENTS:
        name = f"[{c.name}]({c.url})" if c.url else c.name
        rows.append(f"| {name} | {c.license} | {c.role} |")
    return "\n".join(rows)


def third_party() -> str:
    return "\n".join([
        "# Third-party components and licences", "",
        f"pyLogi itself is licensed under the **{credits.LICENSE_NAME}** (SPDX: `{credits.LICENSE_ID}`); "
        "see [LICENSE](LICENSE).",
        "This file is generated by `scripts/gen_docs.py` from `src/pylogi/core/credits.py`, which also feeds the "
        "*About* dialog.", "", components_markdown(), "", "## Trademarks", "", credits.TRADEMARKS, "",
        "## Warranty", "", credits.WARRANTY, ""])


def replace_block(text: str, name: str, body: str) -> str:
    pat = re.compile(rf"(<!-- {name}-START -->\n)(?:.*?\n)?(<!-- {name}-END -->)", re.S)
    if not pat.search(text):
        raise SystemExit(f"README.md has no <!-- {name}-START --> / <!-- {name}-END --> block")
    return pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)


def build() -> dict[Path, str]:
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    readme = replace_block(readme, "CLI", cli_markdown())
    readme = replace_block(readme, "COMPONENTS", components_markdown())
    return {ROOT / "README.md": readme, ROOT / "THIRD_PARTY.md": third_party()}


def main() -> int:
    out = build()
    stale = [p for p, text in out.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        for p in stale:
            print("out of date:", p.relative_to(ROOT))
        return 1 if stale else 0
    for p in stale:
        p.write_text(out[p], encoding="utf-8")
        print("updated", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
